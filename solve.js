// Faster drop-in for makefun-site 1.0.0 (site-generator-speed-01).
// A single-file, dependency-free reimplementation of the reference generator:
// same front matter, template dialect, Markdown subset, slug rule and report,
// byte for byte, but with the hot paths rewritten for speed:
//  - inline Markdown renders in chunked runs instead of one regex replace per character
//  - HTML escaping and slugifying take fast paths (ASCII, cached results)
//  - template rendering pushes into one array and reuses loop scopes instead of
//    allocating a scope object per iteration and concatenating strings per node
//  - front matter is parsed by hand instead of by a regex per line
// No clock, environment, randomness, file, network, model call or native code.

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const RESERVED = ['posts', 'tags', 'page'];

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const HAS_SPECIAL = /[&<>"']/;

export function escapeHtml(text) {
  if (!HAS_SPECIAL.test(text)) return text;
  let out = '';
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const e = ESCAPES[text[i]];
    if (e !== undefined) {
      if (i > start) out += text.slice(start, i);
      out += e;
      start = i + 1;
    }
  }
  if (start < text.length) out += text.slice(start);
  return out;
}

const SLUG_MAX = 64;
const slugCache = new Map();

/** The slug of `text`, exactly as makefun-site's slugify (NFKD, marks dropped, runs of non [a-z0-9] one "-"). */
export function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  let plain = text;
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) > 127) { ascii = false; break; }
  }
  if (!ascii) plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  if (out.length > SLUG_MAX) out = out.slice(0, SLUG_MAX);
  // drop a "-" left at the cut
  let end = out.length;
  while (end > 0 && out[end - 1] === '-') end--;
  if (end !== out.length) out = out.slice(0, end);
  if (out === '') out = 'untitled';
  slugCache.set(text, out);
  return out;
}

export function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

export function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];

function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw[0] === '"') {
    if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw[0] === '[') return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      let y = 0, mo = 0, d = 0;
      if (ok) {
        for (let i = 0; i < 10; i++) {
          if (i === 4 || i === 7) continue;
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) { ok = false; break; }
        }
      }
      if (ok) {
        y = +raw.slice(0, 4); mo = +raw.slice(5, 7); d = +raw.slice(8, 10);
        if (y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) ok = false;
      }
      if (!ok) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (let i = 0; i < tags.length; i++) {
        const t = tags[i];
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      let ok = raw.length > 0;
      for (let i = 0; ok && i < raw.length; i++) {
        const c = raw[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) ok = false;
      }
      return ok ? { value: raw } : { error: 'key "layout": not a template name' };
    }
    case 'slug': {
      let ok = raw.length > 0 && raw.length <= 64;
      let prevDash = true; // a slug may not start with "-"
      for (let i = 0; ok && i < raw.length; i++) {
        const c = raw[i];
        if (c === '-') {
          if (prevDash) ok = false;
          prevDash = true;
        } else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) prevDash = false;
        else ok = false;
      }
      if (prevDash) ok = false;
      return ok ? { value: raw } : { error: 'key "slug": not a slug' };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

export function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') { close = i; break; }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (isBlankLine(line) || line[0] === '#') continue;
    const colon = line.indexOf(':');
    if (colon <= 0) return { error: `line ${i + 1} is not "key: value"` };
    const key = line.slice(0, colon);
    let keyOk = true;
    for (let k = 0; k < key.length; k++) {
      const c = key[k];
      if (!((c >= 'a' && c <= 'z') || c === '_')) { keyOk = false; break; }
    }
    if (!keyOk) return { error: `line ${i + 1} is not "key: value"` };
    let raw;
    if (colon + 1 === line.length) raw = '';
    else if (line[colon + 1] === ' ') raw = line.slice(colon + 2);
    else return { error: `line ${i + 1} is not "key: value"` };
    // drop trailing spaces and tabs
    let end = raw.length;
    while (end > 0 && (raw[end - 1] === ' ' || raw[end - 1] === '\t')) end--;
    if (end !== raw.length) raw = raw.slice(0, end);
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: lines.slice(close + 1).join('\n') };
}

// ---------------------------------------------------------------- markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function isSpaceTab(c) { return c === ' ' || c === '\t'; }

function trimLine(line) {
  let a = 0, b = line.length;
  while (a < b && isSpaceTab(line[a])) a++;
  while (b > a && isSpaceTab(line[b - 1])) b--;
  return line.slice(a, b);
}

function isBlank(line) { return isBlankLine(line); }

/** Fence open: ``` + optional language, then spaces/tabs only; returns the language or null. */
function fenceLang(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let i = 3;
  let lang = '';
  while (i < line.length) {
    const c = line[i];
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-') { lang += c; i++; }
    else break;
  }
  while (i < line.length && isSpaceTab(line[i])) i++;
  return i === line.length ? lang : null;
}

function isFenceClose(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let i = 3; i < line.length; i++) if (!isSpaceTab(line[i])) return false;
  return true;
}

/** A heading line's {depth, text} or null. */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length || !isSpaceTab(line[n])) return null;
  let a = n;
  while (a < line.length && isSpaceTab(line[a])) a++;
  let b = line.length;
  while (b > a && isSpaceTab(line[b - 1])) b--;
  const text = line.slice(a, b);
  return text === '' ? null : { depth: n, text };
}

function isHR(line) {
  if (line.slice(0, 3) !== '---' && line.slice(0, 3) !== '***') return false;
  for (let i = 3; i < line.length; i++) if (!isSpaceTab(line[i])) return false;
  return true;
}

function endsParagraph(line) {
  if (line.length === 0) return true;
  const c = line.charCodeAt(0);
  if (c === 96) return fenceLang(line) !== null; // ` : only a fence can end it
  if (c === 35) return headingOf(line) !== null; // # : only a heading can end it
  if (c === 45 || c === 42) return isHR(line); // - or * : only a thematic break can end it
  if (c === 32 || c === 9) return isBlank(line); // a line of spaces/tabs only is blank
  return false;
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (c !== '*') continue;
    if (s[j + 1] === '*') { j++; continue; }
    return j;
  }
  return -1;
}

function pushEscaped(parts, s, a, b) {
  if (b > a) parts.push(escapeHtml(s.slice(a, b)));
}

const INLINE_SPECIAL = /[\\`*[]/;

/** `s` rendered inline; `link(target)` is a link's href. */
export function inline(s, link) {
  // No backslash, backtick, star or bracket anywhere: the whole string is plain text.
  if (!INLINE_SPECIAL.test(s)) return escapeHtml(s);
  const parts = [];
  let i = 0;
  const n = s.length;
  let plainStart = 0;
  while (i < n) {
    const c = s.charCodeAt(i);
    if (c === 92 && i + 1 < n && ESCAPABLE.has(s[i + 1])) {
      pushEscaped(parts, s, plainStart, i);
      parts.push(escapeHtml(s[i + 1]));
      i += 2;
      plainStart = i;
      continue;
    }
    if (c === 96) {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        pushEscaped(parts, s, plainStart, i);
        parts.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        plainStart = i;
      } else i++;
      continue;
    }
    if (c === 42) {
      if (s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          pushEscaped(parts, s, plainStart, i);
          parts.push('<strong>', inline(s.slice(i + 2, j), link), '</strong>');
          i = j + 2;
          plainStart = i;
        } else i += 2;
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        pushEscaped(parts, s, plainStart, i);
        parts.push('<em>', inline(s.slice(i + 1, j), link), '</em>');
        i = j + 1;
        plainStart = i;
      } else i++;
      continue;
    }
    if (c === 91) {
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        pushEscaped(parts, s, plainStart, i);
        parts.push('<a href="', escapeHtml(link(target)), '">', inline(s.slice(i + 1, k), link), '</a>');
        i = m + 1;
        plainStart = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  pushEscaped(parts, s, plainStart, n);
  return parts.join('');
}

export function renderMarkdown(src, link) {
  const lines = src.split('\n');
  const blocks = [];
  const toc = [];
  let excerpt = null;
  const ids = new Set();
  let i = 0;
  const L = lines.length;
  while (i < L) {
    const line = lines[i];
    if (isBlank(line)) { i++; continue; }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < L && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
      let code = '';
      for (let k = 0; k < body.length; k++) { code += escapeHtml(body[k]); code += '\n'; }
      blocks.push(`<pre><code${cls}>${code}</code></pre>`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, link);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) { blocks.push('<hr>'); i++; continue; }
    if (line[0] === '>') {
      const body = [];
      while (i < L && lines[i][0] === '>') {
        let l = lines[i++];
        l = l.slice(1);
        if (l[0] === ' ') l = l.slice(1);
        body.push(l);
      }
      const trimmed = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimLine(body[k]);
        if (t !== '') trimmed.push(t);
      }
      blocks.push(trimmed.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(trimmed.join('\n'), link)}</p>\n</blockquote>`);
      continue;
    }
    // list?
    let isOrdered = false;
    let startNum = 1;
    let itemText = null;
    if (line[0] === '-' && line[1] === ' ') { itemText = line.slice(2); }
    else if (line[0] === '*' && line[1] === ' ') { itemText = line.slice(2); }
    else {
      let d = 0;
      while (d < line.length && d < 9 && line[d] >= '0' && line[d] <= '9') d++;
      if (d >= 1 && line[d] === '.' && line[d + 1] === ' ' && !(d === 9 && line[9] >= '0' && line[9] <= '9')) {
        isOrdered = true;
        startNum = Number(line.slice(0, d));
        itemText = line.slice(d + 2);
      }
    }
    if (itemText !== null) {
      const items = [];
      let cur = [trimLine(itemText)];
      items.push(cur);
      i++;
      while (i < L) {
        const l = lines[i];
        let mText = null;
        let mOrdered = false;
        if (!isOrdered) {
          if (l[0] === '-' && l[1] === ' ') mText = l.slice(2);
          else if (l[0] === '*' && l[1] === ' ') mText = l.slice(2);
        } else {
          let d = 0;
          while (d < l.length && d < 9 && l[d] >= '0' && l[d] <= '9') d++;
          if (d >= 1 && l[d] === '.' && l[d + 1] === ' ' && !(d === 9 && l[9] >= '0' && l[9] <= '9')) {
            mOrdered = true;
            mText = l.slice(d + 2);
          }
        }
        if (mText !== null) {
          cur = [trimLine(mText)];
          items.push(cur);
          i++;
        } else if (l.length >= 2 && l[0] === ' ' && l[1] === ' ') {
          let sp = 0;
          while (sp < l.length && l[sp] === ' ') sp++;
          if (sp >= 2 && sp < l.length && !/\s/.test(l[sp])) {
            cur.push(trimLine(l));
            i++;
          } else break;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && startNum !== 1 ? `<ol start="${startNum}">` : `<${tag}>`;
      let html = `${open}\n`;
      for (let k = 0; k < items.length; k++) html += `<li>${inline(items[k].join('\n'), link)}</li>\n`;
      html += `</${tag}>`;
      blocks.push(html);
      continue;
    }
    // paragraph
    const body = [trimLine(line)];
    i++;
    while (i < L && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), link);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  return { html: blocks.length === 0 ? '' : `${blocks.join('\n')}\n`, toc, excerpt: excerpt ?? '' };
}

